/**
 * Configuration options for initializing a SnowflakeGenerator.
 *
 * @public
 */
export interface SnowflakeConfig {
    /**
     * A unique identifier for the machine or process generating IDs.
     * Must be an integer between 0 and the layout's maximum machine ID (default 1023).
     */
    machineId: number;

    /**
     * Optional custom epoch in milliseconds.
     * Determines the start date for the timestamp component of the ID.
     * Defaults to January 1, 2024.
     */
    epoch?: number;

    /**
     * Strategy to use when the system clock moves backwards.
     * - 'throw': Immediately throws an Error.
     * - 'wait': Blocks generation until the clock catches up to the last generated timestamp.
     * Defaults to 'throw'.
     */
    clockMoveBackAction?: 'throw' | 'wait';

    /**
     * Optional callback fired when the system clock moves backwards.
     *
     * @param driftMs - The number of milliseconds the clock drifted backwards.
     */
    onClockDrift?: (driftMs: number) => void;

    /**
     * Optional callback fired when the sequence counter overflows its bit allocation
     * within a single millisecond (e.g., generating more than 4096 IDs in one millisecond).
     * The generator will automatically wait for the next millisecond.
     */
    onSequenceOverflow?: () => void;

    /**
     * Optional custom bit layout configuration.
     * If omitted, the default layout (41 timestamp bits, 10 machine bits, 12 sequence bits) is used.
     */
    layout?: SnowflakeLayout;
}

/**
 * The decomposed components of a Snowflake ID.
 *
 * @public
 */
export interface SnowflakeParts {
    /** The original ID as a BigInt. */
    id: bigint;
    /** The extracted timestamp as a JavaScript Date object. */
    timestamp: Date;
    /** The extracted timestamp in milliseconds since the Unix epoch. */
    timestampMs: number;
    /** The extracted machine identifier. */
    machineId: number;
    /** The extracted sequence number. */
    sequence: number;
}

/**
 * A JSON-serializable representation of SnowflakeParts.
 * The ID is represented as a string to prevent precision loss.
 *
 * @public
 */
export interface SnowflakePartsJSON {
    /** The original ID safely encoded as a string. */
    id: string;
    /** The extracted timestamp as an ISO string. */
    timestamp: string;
    /** The extracted timestamp in milliseconds since the Unix epoch. */
    timestampMs: number;
    /** The extracted machine identifier. */
    machineId: number;
    /** The extracted sequence number. */
    sequence: number;
}

/**
 * The current operational status of a SnowflakeGenerator instance.
 *
 * @public
 */
export interface GeneratorStatus {
    /** The configured machine ID. */
    machineId: number;
    /** The configured epoch in milliseconds. */
    epoch: number;
    /** The exact date when the timestamp field will overflow and exhaust ID generation. */
    epochExpiresAt: Date;
    /** The estimated number of years remaining before the epoch expires. */
    remainingYears: number;
    /** The total count of IDs generated by this specific instance since creation. */
    totalIdsGenerated: bigint;
    /** The exact date when the most recent ID was generated, or null if none exist. */
    lastGeneratedAt: Date | null;
    /** A percentage (0.0 to 1.0) indicating how much of the current millisecond's sequence capacity has been used. */
    sequenceUtilization: number;
}

/**
 * A pre-calculated layout configuration defining the bit structure of the Snowflake ID.
 *
 * @public
 */
export interface SnowflakeLayout {
    /** Number of bits reserved for the timestamp. */
    readonly timestampBits: number;
    /** Number of bits reserved for the machine ID. */
    readonly machineBits: number;
    /** Number of bits reserved for the sequence counter. */
    readonly sequenceBits: number;
    /** The time resolution per tick in milliseconds (usually 1, or 10 for Sonyflake). */
    readonly resolution: number;
    /** Bitwise left-shift offset for the timestamp component. */
    readonly timestampShift: bigint;
    /** Bitwise left-shift offset for the machine ID component. */
    readonly machineIdShift: bigint;
    /** Maximum possible value for the timestamp component. */
    readonly maxTimestamp: bigint;
    /** Maximum possible value for the machine ID component. */
    readonly maxMachineId: number;
    /** Maximum possible value for the sequence component. */
    readonly maxSequence: bigint;
    /** Maximum theoretical ID value possible with this layout. */
    readonly maxSnowflakeId: bigint;
    /** The estimated lifespan in years before the timestamp overflows. */
    readonly lifespanYears: number;
    /** The maximum number of IDs that can be generated per millisecond. */
    readonly idsPerMs: number;
}

/**
 * Input configuration for defining a custom Snowflake layout.
 *
 * @public
 */
export interface LayoutConfig {
    /** Configuration for the timestamp bit allocation. */
    timestamp: { bits: number; resolution?: number };
    /** Configuration for the machine ID bit allocation. */
    machine: { bits: number };
    /** Configuration for the sequence counter bit allocation. */
    sequence: { bits: number };
}

/**
 * A bounding range of Snowflake IDs for a specific time window.
 *
 * @public
 */
export interface SnowflakeRange {
    /** The smallest possible ID for the given time window. */
    min: bigint;
    /** The largest possible ID for the given time window. */
    max: bigint;
}

declare const __brand: unique symbol;
declare const __entity: unique symbol;

/**
 * A strictly typed BigInt Snowflake ID bound to a specific entity type string.
 * Prevents accidental mixing of IDs from different domains (e.g., passing a User ID to an Order ID function).
 *
 * @public
 */
export type BrandedSnowflake<Brand extends string> = bigint & {
    readonly [__brand]: typeof __brand;
    readonly [__entity]: Brand;
};

/**
 * A strictly typed string Snowflake ID bound to a specific entity type string.
 * Prevents accidental mixing of IDs from different domains (e.g., passing a User ID to an Order ID function).
 *
 * @public
 */
export type BrandedSnowflakeString<Brand extends string> = string & {
    readonly [__brand]: typeof __brand;
    readonly [__entity]: Brand;
};
